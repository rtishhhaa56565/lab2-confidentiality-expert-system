def normalize(text: str) -> str:
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[\n\r\t]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _has_any(text: str, variants: tuple[str, ...]) -> bool:
    return any(variant in text for variant in variants)


def _has_negated(text: str, word: str) -> bool:
    patterns = (
        rf"не\s+\w*{re.escape(word)}",
        rf"без\s+\w*{re.escape(word)}",
        rf"отсутств\w*\s+\w*{re.escape(word)}",
    )
    return any(re.search(pattern, text) for pattern in patterns)


def extract_facts(text: str) -> Facts:
    """Преобразует текст в набор фактов для механизма логического вывода."""
    normalized = normalize(text)
    facts = Facts(original_text=text, normalized_text=normalized)

    for category, mapping in DICTIONARIES.items():
        target = getattr(facts, category)
        for name, variants in mapping.items():
            if _has_any(normalized, variants):
                target.add(name)

    # Контекст определяется отдельно, в том числе с учётом отрицаний.
    if _has_any(normalized, ("письменное согласие", "письменного согласия", "дал согласие", "с согласия")) and not _has_negated(normalized, "соглас"):
        facts.context.add("согласие")
    if _has_any(normalized, ("без согласия", "согласие не", "согласия нет", "не получено согласие")):
        facts.context.add("нет согласия")
    if _has_any(normalized, ("nda", "соглашение о конфиденциальности", "соглашение подписано")):
        facts.context.add("nda")
    if _has_any(normalized, ("письменный запрос", "письменному запросу", "официальный запрос", "запрос нотариуса")):
        facts.context.add("письменный запрос")
    if _has_any(normalized, ("устный запрос", "устная доверенност", "устной доверенност", "устно")):
        facts.context.add("устное основание")
    if _has_any(normalized, ("письменная доверенность", "нотариальная доверенность")):
        facts.context.add("письменная доверенность")
    if _has_any(normalized, ("проверка", "проверки", "налоговый контроль")):
        facts.context.add("проверка")
    if _has_any(normalized, ("наследств", "умерш", "после смерти")):
        facts.context.add("наследственное дело")
    if _has_any(normalized, ("сделка не состоялась", "несостоявшейся сделки", "сделка сорвалась")):
        facts.context.add("сделка не состоялась")
    if _has_any(normalized, ("по секрету", "тайно", "закрытом профиле")):
        facts.context.add("неофициально")
    if _has_any(normalized, ("внешний аудит", "для аудита", "аудитор")):
        facts.context.add("аудит")
    if _has_any(normalized, ("суд", "решение суда", "судебный")):
        facts.context.add("суд")

    return facts
