"""База правил экспертной системы и механизм логического вывода."""

from dataclasses import dataclass, field
from analyzer import Facts


@dataclass
class Decision:
    status: str
    law: str
    reason: str
    action: str
    questions: list[str] = field(default_factory=list)
    rule_id: str = ""


def _contains(values: set[str], *expected: str) -> bool:
    return any(value in values for value in expected)


def evaluate(facts: Facts) -> list[Decision]:
    """Применяет правила к извлечённым фактам."""
    decisions: list[Decision] = []
    obj, rec, act, ctx = facts.objects, facts.recipients, facts.actions, facts.context

    # R01. Налоговая тайна передана конкуренту.
    if "налоговая тайна" in obj and "конкурент" in rec and _contains(act, "передача", "публикация"):
        decisions.append(Decision("НАРУШЕНИЕ", "ст. 102 НК РФ; возможно ст. 13.14 КоАП РФ или ст. 183 УК РФ", "Налоговые сведения переданы конкуренту без законного основания.", "Заблокировать передачу, сохранить доказательства и провести проверку.", rule_id="R01"))

    # R02. Законная передача налоговому органу для проверки.
    if "налоговая тайна" in obj and "налоговый орган" in rec and "проверка" in ctx:
        decisions.append(Decision("ЗАКОННО", "ст. 82, 93.1 и 102 НК РФ", "Сведения используются налоговым органом в целях налогового контроля.", "Ничего не удалять; передать только необходимый объём по защищённому каналу.", rule_id="R02"))

    # R03–R04. Коммерческая тайна и внешний аудит.
    if "коммерческая тайна" in obj and "аудитор" in rec and "аудит" in ctx:
        if "nda" in ctx:
            decisions.append(Decision("ЗАКОННО", "Федеральный закон № 98-ФЗ; условия NDA", "Передача аудитору ограничена целью аудита и соглашением о конфиденциальности.", "Передать минимальный объём и зарегистрировать доступ.", rule_id="R03"))
        else:
            decisions.append(Decision("ТРЕБУЕТСЯ РУЧНАЯ ПРОВЕРКА", "Федеральный закон № 98-ФЗ", "Не найдено соглашение о конфиденциальности с внешним аудитором.", "До проверки не передавать сведения.", ["Подписано ли NDA?", "Каков перечень передаваемых сведений?"], "R04"))

    # R05. Использование данных после несостоявшейся сделки.
    if "коммерческая тайна" in obj and "использование" in act and "сделка не состоялась" in ctx:
        decisions.append(Decision("НАРУШЕНИЕ", "ст. 434.1, 1465–1472 ГК РФ; Федеральный закон № 98-ФЗ", "Конфиденциальные сведения использованы за пределами цели переговоров.", "Прекратить использование и зафиксировать происхождение сведений.", rule_id="R05"))

    # R06. Публикация исходного кода.
    if "коммерческая тайна" in obj and "публикация" in act and "социальная сеть" in rec:
        decisions.append(Decision("НАРУШЕНИЕ", "ст. 10–11 Федерального закона № 98-ФЗ", "Исходный код раскрыт неопределённому или постороннему кругу лиц.", "Удалить публикацию, сохранить доказательства и провести служебную проверку.", rule_id="R06"))

    # R07–R08. Персональные данные третьему лицу.
    if "персональные данные" in obj and "третье лицо" in rec and "передача" in act:
        if "согласие" in ctx and "нет согласия" not in ctx:
            decisions.append(Decision("ЗАКОННО", "ст. 6 и 9 Федерального закона № 152-ФЗ", "Найдено указание на письменное согласие субъекта.", "Проверить объём согласия и передать только разрешённые данные.", rule_id="R07"))
        else:
            decisions.append(Decision("НАРУШЕНИЕ", "ст. 6, 7 и 9 Федерального закона № 152-ФЗ", "Персональные данные передаются третьему лицу без подтверждённого основания.", "Заблокировать передачу или обезличить данные.", rule_id="R08"))

    # R09–R10. Нотариус и банковская тайна.
    if "банковская тайна" in obj and "нотариус" in rec and "наследственное дело" in ctx:
        if "отказ" in act and "письменный запрос" in ctx:
            decisions.append(Decision("НАРУШЕНИЕ", "ст. 26 Федерального закона № 395-1", "Банк отказал нотариусу при надлежащем запросе по наследственному делу.", "Предоставить сведения в пределах запроса.", rule_id="R09"))
        elif "письменный запрос" in ctx:
            decisions.append(Decision("ЗАКОННО", "ст. 26 Федерального закона № 395-1", "Нотариус вправе получить сведения по наследственному делу.", "Передать сведения по защищённому каналу и зарегистрировать выдачу.", rule_id="R10"))
        else:
            decisions.append(Decision("ТРЕБУЕТСЯ РУЧНАЯ ПРОВЕРКА", "ст. 26 Федерального закона № 395-1", "Не подтверждены форма запроса и полномочия нотариуса.", "Запросить официальный документ.", ["Есть ли номер наследственного дела?", "Подписан ли запрос нотариусом?"], "R11"))

    # R12. Росфинмониторинг.
    if "банковская тайна" in obj and "росфинмониторинг" in rec and "передача" in act:
        decisions.append(Decision("ЗАКОННО", "ст. 7 Федерального закона № 115-ФЗ; ст. 26 Закона № 395-1", "Передача в Росфинмониторинг является предусмотренным законом исключением.", "Ничего не удалять; не раскрывать клиенту содержание сообщения.", rule_id="R12"))

    # R13–R14. Адвокат и доверенность.
    if "банковская тайна" in obj and "адвокат" in rec:
        if "письменная доверенность" in ctx:
            decisions.append(Decision("ЗАКОННО", "ст. 185 ГК РФ; ст. 26 Закона № 395-1", "Полномочия представителя подтверждены письменной доверенностью.", "Проверить срок и объём полномочий перед выдачей.", rule_id="R13"))
        elif "устное основание" in ctx and "отказ" in act:
            decisions.append(Decision("ЗАКОННО", "ст. 185 ГК РФ; ст. 26 Закона № 395-1", "Устной доверенности недостаточно, поэтому отказ банка обоснован.", "Запросить письменную доверенность.", rule_id="R14"))

    # R15–R16. Врачебная тайна и полиция.
    if "врачебная тайна" in obj and "полиция" in rec and _contains(act, "передача", "запрос"):
        if "письменный запрос" in ctx or "суд" in ctx:
            decisions.append(Decision("ЗАКОННО", "ч. 4 ст. 13 Федерального закона № 323-ФЗ", "Имеется документированное законное основание для передачи.", "Передать минимально необходимые сведения и зарегистрировать выдачу.", rule_id="R15"))
        elif "устное основание" in ctx:
            decisions.append(Decision("НАРУШЕНИЕ", "ст. 13 Федерального закона № 323-ФЗ", "Расширенные медицинские сведения передаются только по устному запросу.", "Не передавать медицинскую документацию; запросить письменное основание.", rule_id="R16"))

    # R17. Разглашение диагноза постороннему.
    if "врачебная тайна" in obj and "третье лицо" in rec and _contains(act, "передача", "публикация"):
        decisions.append(Decision("НАРУШЕНИЕ", "ст. 13 Федерального закона № 323-ФЗ", "Сведения о диагнозе раскрыты постороннему лицу без установленного основания.", "Прекратить распространение, удалить публикацию и провести проверку.", rule_id="R17"))

    # R18. Иностранный запрос требует отдельной проверки.
    if "иностранный орган" in rec and _contains(obj, "налоговая тайна", "банковская тайна", "врачебная тайна", "персональные данные"):
        decisions.append(Decision("ТРЕБУЕТСЯ РУЧНАЯ ПРОВЕРКА", "международный договор РФ и профильный федеральный закон", "Необходимо проверить компетенцию органа и международный канал обмена.", "До проверки не передавать сведения.", ["Какое государство направило запрос?", "Есть ли применимый международный договор?", "Запрос поступил через компетентный орган РФ?"], "R18"))

    # R19. Возможная государственная тайна не относится к предмету автоматического решения.
    if "государственная тайна" in obj:
        decisions.append(Decision("ТРЕБУЕТСЯ РУЧНАЯ ПРОВЕРКА", "Закон РФ № 5485-1 «О государственной тайне»", "Обнаружены признаки сведений, которые могут иметь иной режим охраны.", "Не распространять текст и передать специалисту по защите информации.", ["Имеет ли объект гриф секретности?", "Откуда получены сведения?"], "R19"))

    if not decisions:
        decisions.append(Decision("ТРЕБУЕТСЯ РУЧНАЯ ПРОВЕРКА", "Основание не определено", "Недостаточно фактов для однозначного вывода.", "Сохранить текст и направить ответственному специалисту.", _default_questions(facts), "R00"))

    return decisions


def _default_questions(facts: Facts) -> list[str]:
    questions = []
    if not facts.objects:
        questions.append("Какой вид конфиденциальной информации затронут?")
    if not facts.recipients:
        questions.append("Кому передаются или раскрываются сведения?")
    if not facts.actions:
        questions.append("Какое действие было совершено?")
    if "согласие" not in facts.context and "нет согласия" not in facts.context:
        questions.append("Получено ли письменное согласие или иное законное основание?")
    return questions or ["Уточните цель, получателя и документальное основание обработки."]

